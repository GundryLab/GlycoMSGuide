export type OffsetMagnitude = "all" | "0" | "1" | "2";

export function filterCompositionConfusions(query: string, magnitude: OffsetMagnitude) {
  const normalized = query.replace(/\s+/g, "").toLowerCase();
  return compositionConfusions.filter(({ row, column, offset }) => {
    const matchesOffset = magnitude === "all" || Math.abs(offset) === Number(magnitude);
    const matchesQuery = [confusionCompositions[row], confusionCompositions[column]].some(
      (entry) => [entry.composition, entry.glytoucanId].some((value) => value.toLowerCase().includes(normalized)),
    );
    return matchesOffset && matchesQuery;
  });
}

export function formatIsotopeOffset(offset: number): string {
  return offset === 0 ? "0" : offset > 0 ? `+${offset}` : `−${Math.abs(offset)}`;
}
