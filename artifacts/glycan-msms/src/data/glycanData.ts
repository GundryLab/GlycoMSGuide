/** Exposed for tests: every rule must point at an ion that exists in the dataset. */
export const glytoucanOverrideRules: readonly GlyTouCanOverrideRule[] = ionGlytoucanOverrides;

function findGlytoucanOverride(ion: DiagnosticIon): GlyTouCanEntry[] | undefined {
  return ionGlytoucanOverrides.find(
    (rule) =>
      Math.abs(rule.mz - ion.mz) < 0.00005 &&
      rule.polarity === ion.polarity &&
      (!rule.descriptionMatch || rule.descriptionMatch.test(ion.description)),
  )?.entries;
}


export type GlyTouCanContext = "exact" | "precursor" | "none";

export function getGlytoucanContext(ion: DiagnosticIon): GlyTouCanContext {
  const ionType = (ion.ionType || "").toLowerCase();
  if (ionType === "fragment" || ionType === "a-ion") return "none";
  if (ionType === "y-ion" || ionType === "c-ion") return "exact";
  if (ionType === "b-ion" || ionType === "z-ion") return "precursor";
  if (ionType === "d-ion") return "precursor";
  if (ionType === "oxonium") return "precursor";
  if (!ion.ionType && ion.monosaccharides && ion.monosaccharides.length === 1) return "exact";
  return "precursor";
}

export function getGlytoucanLabel(context: GlyTouCanContext): string {
  if (context === "exact") return "GlyTouCan structure:";
  return "GlyTouCan (intact precursor):";
}

export function getGlytoucanTooltip(context: GlyTouCanContext): string {
  if (context === "exact") {
    return "GlyTouCan ID represents this intact glycan structure (Y/C-type ion retains the complete glycosidic structure).";
  }
  return "GlyTouCan ID is a possible intact structural context, not an assignment proven by this fragment. B-type and oxonium ions alone do not establish linkage or topology.";
}

export function getGlytoucanIdsForIon(ion: DiagnosticIon): GlyTouCanEntry[] {
  if (getGlytoucanContext(ion) === "none") return [];

  const seen = new Set<string>();
  const entries: GlyTouCanEntry[] = [];

  const overrides = findGlytoucanOverride(ion);
  if (overrides) {
    for (const entry of overrides) {
      entries.push(entry);
      seen.add(entry.id);
    }
  }

  if (ion.monosaccharides) {
    const uniqueMonos = [...new Set(ion.monosaccharides)];
    for (const mono of uniqueMonos) {
      const mapped = glytoucanMap[mono];
      if (mapped) {
        for (const entry of mapped) {
          if (!seen.has(entry.id)) {
            entries.push(entry);
            seen.add(entry.id);
          }
        }
      }
    }
  }

  return entries;
}

export interface IonEvidence {
  /** Key into `references` (e.g. "harvey2005c"). */
  sourceKey: string;
  /** Table, figure or page in the source where the ion is reported. */
  locator: string;
  /** m/z exactly as printed in the source (sources differ in precision). */
  reportedMz: string;
  /** Assignment as given by the source. */
  reportedAssignment: string;
  /** primary_observation: the source reports the ion in its own (or re-analysed public) data.
   *  compilation: a peer-reviewed compilation that names the primary studies (listed in primaryReferences). */
  evidenceType: "primary_observation" | "compilation";
  primaryReferences?: string[];
  /** Ion mode, activation and sample context of the observation. */
  context: string;
}

export interface WithdrawnDiagnosticIon {
  mz: number;
  polarity: "positive" | "negative";
  description: string;
  originalSource: string;
  reason: string;
}

export interface DiagnosticIon {
  /** Monoisotopic m/z, 4 decimals; must equal the value computed from `formula` and `charge`. */
  mz: number;
  /** Elemental formula of the ion itself (Hill order, ASCII digits). */
  formula: string;
  /** Signed charge of the ion; sign must agree with `polarity`. */
  charge: 1 | -1;
  /** "source": at least one evidence record naming a table/figure/page.
   *  "calculated": composition and m/z are calculated; no primary source located yet (evidence is empty; see evidenceNote). */
  verification: "source" | "calculated";
  evidence: IonEvidence[];
  /** For calculated ions: what has been checked and what source is still needed. */
  evidenceNote?: string;
  /** Internal curation note (included in the JSON download). */
  curationNote?: string;
  description: string;
  composition: string;
  category: "monosaccharide" | "glycan_type" | "motif" | "modification" | "glycopeptide" | "oxonium";
  subCategory?: string;
  notes?: string;
  ionType?: string;
  polarity: "positive" | "negative";
  source: string;
  monosaccharides?: string[];
}

